"""Stage the release package for the published corpus.

Copies exactly the files that back the published rounds, plus the documents a
reader needs to interpret them, into one directory, and writes a checksum file
that covers only that directory. The point is that a third party can download a
small tree and verify it without cloning 2.4 GB of development data.

Which rounds are published comes from `data/manifest.json` (`published_corpus`),
which is regenerated by `tools/corpus_register.py`; nothing is listed by hand.

Default payload per round is the export and its metadata. The per-sample
telemetry (`*.ndjson`) is 194 MB of the 223 MB the published rounds occupy, so
it is opt-in through `--with-telemetry`; the export already carries the decoded
pressure, voltage and envelope that the frozen estimators consume.

    python tools/release_package.py --out dist/bp_waveforms_20261126
    python tools/release_package.py --out dist/full --with-telemetry
"""
import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / 'data' / 'raw'
MANIFEST = ROOT / 'data' / 'manifest.json'

# Documents that must ship with the waveforms: how they were captured, what the
# fields mean, what may be claimed, and what the axis is.
DOCUMENTS = [
    'README.md',
    'LICENSE',
    'LICENSE.md',
    'CITATION.cff',
    'data/LICENSE',
    'data/README.md',
    'data/capture_protocol_v1.md',
    'data/dataset_dictionary.md',
    'data/manifest.csv',
    'data/manifest.json',
    'data/reports/dataset_scope_statement.md',
    'data/reports/dataset_limitations.md',
    'data/reports/statistics_convention_20261111.md',
    'data/reports/pressure_axis_refit_20261126.md',
    'data/reports/pressure_axis_rebook_20261126.md',
    'data/reports/freeze_v6_20261126.md',
    'data/reports/v5_validation_20261114.md',
    'data/reports/crosstday_verdict_20261125.md',
    'data/protocols/reference_bp_freeze_v1.json',
    'data/protocols/reference_bp_freeze_v2.json',
    'data/protocols/reference_bp_freeze_v3.json',
    'data/protocols/reference_bp_freeze_v6.json',
]

SUFFIXES = ['.export.ndjson', '.metadata.json']
TELEMETRY = '.ndjson'


def published_rows():
    payload = json.loads(MANIFEST.read_text(encoding='utf-8'))
    rows = [r for r in payload['rows'] if r.get('published_corpus')]
    if not rows:
        sys.exit('refusing to stage: manifest lists no published round')
    return sorted(rows, key=lambda r: r['run_id'])


def round_files(run_id, with_telemetry):
    """Return the files that belong to one round, or exit naming the gap."""
    found = {}
    for suffix in SUFFIXES + ([TELEMETRY] if with_telemetry else []):
        matches = [p for p in RAW.rglob(run_id + suffix)
                   if suffix != TELEMETRY or not p.name.endswith('.export.ndjson')]
        if len(matches) != 1:
            sys.exit(f'refusing to stage: {len(matches)} file(s) matched '
                     f'{run_id}{suffix}')
        found[suffix] = matches[0]
    return found


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', required=True, help='staging directory to create')
    ap.add_argument('--with-telemetry', action='store_true',
                    help='also copy *.ndjson per-sample telemetry (~194 MB)')
    ap.add_argument('--force', action='store_true', help='replace an existing directory')
    args = ap.parse_args()

    out = Path(args.out)
    if not out.is_absolute():
        out = (ROOT / out).resolve()
    if out.exists():
        if not args.force:
            sys.exit(f'refusing to stage: {out} already exists (use --force)')
        shutil.rmtree(out)
    out.mkdir(parents=True)

    rows = published_rows()

    written = []
    for name in DOCUMENTS:
        source = ROOT / name
        if not source.is_file():
            sys.exit(f'refusing to stage: document missing: {name}')
        target = out / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        written.append(target)

    corpus = out / 'data' / 'raw'
    for row in rows:
        for suffix, source in round_files(row['run_id'], args.with_telemetry).items():
            target = corpus / source.name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
            written.append(target)

    listing = {
        'generated_from_manifest': 'data/manifest.json',
        'published_rounds': len(rows),
        # +1 for release.json itself, which is written below and covered by the
        # checksum file; the count is fixed before writing so the two agree.
        'files': len(written) + 1,
        'bytes': sum(p.stat().st_size for p in written),
        'with_telemetry': bool(args.with_telemetry),
        'tiers': {},
        'gate': {},
        'axis': {
            'captures_in_this_package':
                '82.326 mmHg/V and -19.887 mmHg (all published rounds predate '
                'the 2026-11-26 refit)',
            'firmware_after_refit': '81.529 mmHg/V and -20.03 mmHg',
            'note': 'read begin.slope and begin.intercept from each export '
                    'instead of hard-coding either axis',
        },
    }
    for row in rows:
        listing['tiers'][row['tier']] = listing['tiers'].get(row['tier'], 0) + 1
        listing['gate'][row['gate']] = listing['gate'].get(row['gate'], 0) + 1
    release_json = out / 'release.json'
    release_json.write_text(
        json.dumps(listing, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    written.append(release_json)

    # release.json is written before the checksum file so that it is covered by
    # it: a listed-but-absent or present-but-unlisted file both fail verification.
    lines = []
    for path in sorted(written):
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        lines.append(f'{digest}  {path.relative_to(out).as_posix()}')
    if len(lines) != len({line.split('  ', 1)[1] for line in lines}):
        sys.exit('refusing to write: duplicate paths in the release manifest')
    if len(lines) != listing['files']:
        sys.exit(f'refusing to write: staged {len(lines)} file(s) '
                 f'but release.json declares {listing["files"]}')
    checksum = out / 'checksums.sha256'
    checksum.write_text('\n'.join(lines) + '\n', encoding='utf-8')

    print(f'{len(rows)} published round(s), {len(lines)} file(s), '
          f'{listing["bytes"] / 1e6:.1f} MB')
    print(f'tiers {listing["tiers"]}')
    print(f'gate  {listing["gate"]}')
    print(f'wrote {out}')
    print(f'wrote {checksum}')
    if not args.with_telemetry:
        print('note: per-sample telemetry omitted (pass --with-telemetry to include it)')


if __name__ == '__main__':
    main()
